import { useCallback, useEffect, useRef, useState } from "react";
import {
  Board,
  COLS,
  DROP_SPEED_MS,
  LINES_TARGET,
  Piece,
  ROWS,
  TETROMINOS,
  checkCollision,
  clearLinesPure,
  createBoard,
  hardDropDistance,
  placePieceOnBoardPure,
  rotate,
} from "@/app/lib/tetris/engine";
import { createPieceGenerator } from "@/app/lib/tetris/rng";

export type { Cell, Board, Piece } from "@/app/lib/tetris/engine";
export { LINES_TARGET, hardDropDistance, ROWS, COLS };

export const TIMER_TICK_MS = 10;
export const HOLD_INITIAL_DELAY = 300;
export const HOLD_REPEAT_RATE = 100;

export type TetrisActionType =
  | "left"
  | "right"
  | "softDrop"
  | "tick"
  | "rotateLeft"
  | "rotateRight"
  | "pause"
  | "resume"
  | "end";

export type TetrisAction = { type: TetrisActionType; t: number };

// ───── GameState ──────────
interface GameState {
  board: Board;
  piece: Piece;
  nextPiece: Piece;
  pos: { x: number; y: number };
  lines: number;
  elapsedMs: number;
  gameCompleted: boolean;
  gameOver: boolean;
  lockVisual?: boolean; // renders the board "frozen" for an instant on completion
  lockBoard?: Board;
}

// IMPORTANT (hydration fix): this function is also used as useState's initial
// value, which runs both on the server (SSR) and on the client's first
// render. The initial piece is ALWAYS deterministic (TETROMINOS[0]); the
// real piece (derived from the seed the server issues) is assigned after
// mount, when /api/tetris/new-game responds.
const initialGameState = (): GameState => ({
  board: createBoard(),
  piece: TETROMINOS[0],
  nextPiece: TETROMINOS[0],
  pos: { x: Math.floor(COLS / 2) - 1, y: 0 },
  lines: 0,
  elapsedMs: 0,
  gameCompleted: false,
  gameOver: false,
});

export interface UseTetrisOptions {
  /**
   * Called exactly once when the game is completed, with the nonce and the
   * action log so the backend can replay and validate it. It may return
   * (or resolve to) the time confirmed by the server, which is adopted as
   * the final elapsedMs.
   */
  onComplete?: (
    nonce: string,
    actions: TetrisAction[]
  ) => void | Promise<number | null>;
}

/**
 * Hook with all the game logic and effects (board, active piece, gravity,
 * timer, keyboard, start/stop). Contains nothing UI-related.
 *
 * Pieces no longer come from Math.random(): they are generated by a seeded
 * PRNG whose seed is issued by /api/tetris/new-game (app/lib/tetris/rng.ts),
 * and every player action is logged with its timestamp relative to the start
 * of the game (app/lib/tetris/replay.ts uses it to replay and validate the
 * whole game on the backend before saving the score).
 *
 * SYNCHRONOUS MODEL (important): all game state lives in `stateRef` as the
 * source of truth, and every action (move, rotate, soft-drop, gravity) is
 * processed SYNCHRONOUSLY against that ref, exactly like the server replay
 * does (app/lib/tetris/replay.ts). React only gets a copy for rendering.
 * This used to be done with setState updaters + an asynchronous
 * `pendingLock`, which opened a race window: moving the piece right at the
 * instant of the lock, the action was recorded in the log but the client
 * discarded it (late updater) while the server did apply it to the next
 * piece → desynced board ("Target not reached") and pieces that "sank".
 * By applying each action immediately and logging it at the SAME instant,
 * the order of application always matches the log's, so client and server
 * reproduce identical boards.
 */
export function useTetris({ onComplete }: UseTetrisOptions = {}) {
  const [gameState, setGameState] = useState<GameState>(initialGameState());
  const [ready, setReady] = useState(false);
  const [loading, setLoading] = useState(false);

  // Synchronous source of truth for the state. Every mutation reads
  // stateRef.current, computes the next state and publishes it with
  // applyState (which updates the ref AND the React state at once). Since JS
  // callbacks are atomic (single thread), gravity, keyboard and soft-drop
  // never step on each other: each one sees the already-applied result of
  // the previous one.
  const stateRef = useRef<GameState>(gameState);

  const startTimeRef = useRef<number | null>(null);
  const gameCompletedRef = useRef(false);
  const activeKeysRef = useRef<Set<string>>(new Set());
  const holdTimersRef = useRef<
    Map<string, ReturnType<typeof setTimeout | typeof setInterval>>
  >(new Map());

  // Nonce/seed of the current game (issued by the server) and the action
  // log for the validation replay.
  const nonceRef = useRef<string | null>(null);
  const pieceGenRef = useRef<(() => Piece) | null>(null);
  const gameStartRef = useRef<number | null>(null); // t=0 anchor for the action log
  const actionsRef = useRef<TetrisAction[]>([]);
  // Incremented on every startNewGame call and in stopGame. If two calls
  // overlap (a START fired before a previous one resolved, or a STOP while
  // the request is in flight), whichever is NOT the most recent when it
  // resolves is discarded entirely — without touching any shared ref — so
  // nonce/seed from two different games never get mixed.
  const gameGenerationRef = useRef(0);

  const {
    board,
    piece,
    nextPiece,
    pos,
    lines,
    elapsedMs,
    gameCompleted,
    gameOver,
    lockVisual,
    lockBoard,
  } = gameState;

  // Publishes a new state: updates the authoritative ref SYNCHRONOUSLY and
  // then requests the re-render. Functional updaters are never used for the
  // game logic: the ref already guarantees each action starts from the most
  // recent state, regardless of when React commits.
  const applyState = useCallback((next: GameState) => {
    stateRef.current = next;
    setGameState(next);
  }, []);

  const logAction = useCallback((type: TetrisActionType) => {
    const t = gameStartRef.current != null ? Date.now() - gameStartRef.current : 0;
    actionsRef.current.push({ type, t });
  }, []);

  const drawPiece = useCallback((): Piece => {
    return pieceGenRef.current ? pieceGenRef.current() : TETROMINOS[0];
  }, []);

  const startNewGame = useCallback(async () => {
    const myGeneration = ++gameGenerationRef.current;
    setReady(false);
    setLoading(true);
    try {
      const res = await fetch("/bookmarks/api/tetris/new-game", { method: "POST" });
      if (!res.ok) throw new Error("Failed to start a new game");
      const data = await res.json();

      if (gameGenerationRef.current !== myGeneration) {
        // A more recent startNewGame call is already in progress (or has
        // finished, or the user pressed STOP): this response arrived late and
        // is discarded without touching nonceRef/pieceGenRef/gameStartRef/actionsRef.
        return null;
      }

      nonceRef.current = data.nonce;
      gameStartRef.current = Date.now();
      pieceGenRef.current = createPieceGenerator(data.seed);
      // The game no longer supports manual pause: it starts immediately, so
      // the log always carries a "resume" at t=0 so the server replay clears
      // its internal pause flag (see replay.ts).
      actionsRef.current = [{ type: "resume", t: 0 }];
      setReady(true);

      // Two pieces are drawn: the current one and the next (for the preview).
      // The server only consumes one piece at the start and one per lock
      // (lockAndAdvance), so this extra look-ahead on the client doesn't
      // desync the replay: the "current" piece at any point in the game
      // always matches the same generator call the server uses at that
      // same point.
      const firstPiece = pieceGenRef.current();
      const previewPiece = pieceGenRef.current();
      return { piece: firstPiece, nextPiece: previewPiece };
    } catch (error) {
      console.error("Error starting tetris game:", error);
      if (gameGenerationRef.current === myGeneration) setReady(false);
      return null;
    } finally {
      if (gameGenerationRef.current === myGeneration) setLoading(false);
    }
  }, []);

  /**
   * lockAndAdvance: locks the piece onto the board, clears lines and advances
   * to the next one. Same procedure (and same piece-consumption order) as the
   * server replay. The only asynchronous part is the 80ms "flash" when the
   * game is COMPLETED, which is terminal and therefore can't desync anything:
   * no more actions are processed after that.
   */
  const lockAndAdvance = useCallback(
    (s: GameState): void => {
      const placed = placePieceOnBoardPure(s.board, s.piece, s.pos);
      const { newBoard: clearedBoard, cleared } = clearLinesPure(placed);
      const totalLines = s.lines + cleared;

      const spawnedPiece = s.nextPiece;
      const upcomingPiece = drawPiece();
      const nextPos = { x: Math.floor(COLS / 2) - 1, y: 0 };
      const isGameOver = checkCollision(clearedBoard, spawnedPiece, nextPos.x, nextPos.y);
      const isCompleted =
        !isGameOver && totalLines >= LINES_TARGET && !gameCompletedRef.current;

      if (isCompleted) {
        // Brief flash of the board with the piece already placed (lines not
        // cleared yet) before finishing and submitting the score.
        applyState({ ...s, lockVisual: true, lockBoard: placed });
        setTimeout(() => {
          gameCompletedRef.current = true;
          const finalMs =
            startTimeRef.current != null
              ? Date.now() - startTimeRef.current
              : s.elapsedMs;
          applyState({
            ...stateRef.current,
            board: clearedBoard,
            lines: totalLines,
            piece: spawnedPiece,
            nextPiece: upcomingPiece,
            pos: nextPos,
            gameCompleted: true,
            gameOver: false,
            elapsedMs: finalMs,
            lockVisual: false,
            lockBoard: undefined,
          });
          if (nonceRef.current) {
            logAction("end");
            const nonce = nonceRef.current;
            const actions = [...actionsRef.current];
            const result = onComplete?.(nonce, actions);
            if (result && typeof (result as Promise<number | null>).then === "function") {
              (result as Promise<number | null>).then((confirmed) => {
                if (typeof confirmed === "number") {
                  applyState({ ...stateRef.current, elapsedMs: confirmed });
                }
              });
            }
          }
        }, 80); // brief visual lock flash
        return;
      }
      if (isGameOver) {
        applyState({
          ...s,
          board: clearedBoard,
          lines: totalLines,
          gameOver: true,
          lockVisual: false,
          lockBoard: undefined,
        });
        return;
      }
      applyState({
        ...s,
        board: clearedBoard,
        lines: totalLines,
        piece: spawnedPiece,
        nextPiece: upcomingPiece,
        pos: nextPos,
        lockVisual: false,
        lockBoard: undefined,
      });
    },
    [drawPiece, logAction, onComplete, applyState]
  );

  // Moves the piece down one row; if it collides, locks it. Equivalent to the
  // server replay's descendOrLock. Processed SYNCHRONOUSLY against stateRef.
  const descendOrLock = useCallback(
    (s: GameState): void => {
      const nextY = s.pos.y + 1;
      if (!checkCollision(s.board, s.piece, s.pos.x, nextY)) {
        applyState({ ...s, pos: { ...s.pos, y: nextY } });
      } else {
        lockAndAdvance(s);
      }
    },
    [applyState, lockAndAdvance]
  );

  // ── Player actions and gravity ──
  // They all follow the same pattern: if the game isn't ready or has already
  // ended (or is in the completion flash), they do nothing AND log nothing.
  // Otherwise they log their action and apply it immediately with exactly
  // the same guards as the server replay (collision). That way the log
  // always reflects what the client applied, in the same order.

  const moveLeft = useCallback(() => {
    const s = stateRef.current;
    if (!ready || s.gameCompleted || s.gameOver || s.lockVisual) return;
    logAction("left");
    if (!checkCollision(s.board, s.piece, s.pos.x - 1, s.pos.y)) {
      applyState({ ...s, pos: { ...s.pos, x: s.pos.x - 1 } });
    }
  }, [ready, logAction, applyState]);

  const moveRight = useCallback(() => {
    const s = stateRef.current;
    if (!ready || s.gameCompleted || s.gameOver || s.lockVisual) return;
    logAction("right");
    if (!checkCollision(s.board, s.piece, s.pos.x + 1, s.pos.y)) {
      applyState({ ...s, pos: { ...s.pos, x: s.pos.x + 1 } });
    }
  }, [ready, logAction, applyState]);

  const softDrop = useCallback(() => {
    const s = stateRef.current;
    if (!ready || s.gameCompleted || s.gameOver || s.lockVisual) return;
    logAction("softDrop");
    descendOrLock(s);
  }, [ready, logAction, descendOrLock]);

  const rotatePiece = useCallback(
    (direction: 1 | -1) => {
      const s = stateRef.current;
      if (!ready || s.gameCompleted || s.gameOver || s.lockVisual) return;
      logAction(direction === 1 ? "rotateRight" : "rotateLeft");
      const times = direction === 1 ? 1 : 3;
      let rotated = s.piece.shape;
      for (let i = 0; i < times; i++) rotated = rotate(rotated);
      const rotatedPiece = { ...s.piece, shape: rotated };
      for (const kick of [0, -1, 1, -2, 2]) {
        if (!checkCollision(s.board, rotatedPiece, s.pos.x + kick, s.pos.y)) {
          applyState({
            ...s,
            piece: rotatedPiece,
            pos: { ...s.pos, x: s.pos.x + kick },
          });
          return;
        }
      }
    },
    [ready, logAction, applyState]
  );

  const rotateLeft = useCallback(() => rotatePiece(-1), [rotatePiece]);
  const rotateRight = useCallback(() => rotatePiece(1), [rotatePiece]);

  // Gravity. Each automatic drop is logged as just another "tick" action in
  // the same log as left/right/softDrop — the server does NOT infer gravity
  // from elapsed time (the browser's real setInterval isn't perfectly
  // precise: in long games, hundreds of ticks each accumulating a few ms of
  // delay made the replay apply more drops than actually happened).
  const gravityTick = useCallback(() => {
    const s = stateRef.current;
    if (s.gameCompleted || s.gameOver || s.lockVisual) return;
    logAction("tick");
    descendOrLock(s);
  }, [logAction, descendOrLock]);

  // Timer tick
  useEffect(() => {
    if (!ready || gameCompleted || gameOver) return;
    const id = setInterval(() => {
      const s = stateRef.current;
      if (s.gameCompleted || s.gameOver) return;
      const elapsed =
        startTimeRef.current != null ? Date.now() - startTimeRef.current : s.elapsedMs;
      applyState({ ...s, elapsedMs: elapsed });
    }, TIMER_TICK_MS);
    return () => clearInterval(id);
  }, [ready, gameCompleted, gameOver, applyState]);

  // Gravity
  useEffect(() => {
    if (!ready || gameCompleted || gameOver) return;
    const id = setInterval(gravityTick, DROP_SPEED_MS);
    return () => clearInterval(id);
  }, [ready, gameCompleted, gameOver, gravityTick]);

  // Key repeat (holding the key moves repeatedly)
  const startRepeat = useCallback((key: string, action: () => void) => {
    if (activeKeysRef.current.has(key)) return;
    activeKeysRef.current.add(key);
    action();
    const timeout = setTimeout(() => {
      const interval = setInterval(action, HOLD_REPEAT_RATE);
      holdTimersRef.current.set(key + "_interval", interval);
    }, HOLD_INITIAL_DELAY);
    holdTimersRef.current.set(key, timeout);
  }, []);

  const stopRepeat = useCallback((key: string) => {
    activeKeysRef.current.delete(key);
    const timeout = holdTimersRef.current.get(key);
    if (timeout != null) {
      clearTimeout(timeout as ReturnType<typeof setTimeout>);
      holdTimersRef.current.delete(key);
    }
    const interval = holdTimersRef.current.get(key + "_interval");
    if (interval != null) {
      clearInterval(interval as ReturnType<typeof setInterval>);
      holdTimersRef.current.delete(key + "_interval");
    }
  }, []);

  // Keyboard handler
  useEffect(() => {
    const onKeyDown = (e: KeyboardEvent) => {
      if (e.repeat) return;
      switch (e.key) {
        case "ArrowLeft":
        case "a":
        case "A":
          e.preventDefault();
          startRepeat("left", moveLeft);
          break;
        case "ArrowRight":
        case "d":
        case "D":
          e.preventDefault();
          startRepeat("right", moveRight);
          break;
        case "ArrowDown":
        case "s":
        case "S":
          e.preventDefault();
          startRepeat("down", softDrop);
          break;
        case "o":
        case "O":
          e.preventDefault();
          rotateLeft();
          break;
        case "p":
        case "P":
          e.preventDefault();
          rotateRight();
          break;
        default:
          break;
      }
    };
    const onKeyUp = (e: KeyboardEvent) => {
      switch (e.key) {
        case "ArrowLeft":
        case "a":
        case "A":
          stopRepeat("left");
          break;
        case "ArrowRight":
        case "d":
        case "D":
          stopRepeat("right");
          break;
        case "ArrowDown":
        case "s":
        case "S":
          stopRepeat("down");
          break;
        default:
          break;
      }
    };
    window.addEventListener("keydown", onKeyDown);
    window.addEventListener("keyup", onKeyUp);
    return () => {
      window.removeEventListener("keydown", onKeyDown);
      window.removeEventListener("keyup", onKeyUp);
    };
  }, [moveLeft, moveRight, softDrop, rotateLeft, rotateRight, startRepeat, stopRepeat]);

  // START: starts a new game (both the first one and any restart after a
  // STOP/game over/completion).
  const startGame = useCallback(() => {
    gameCompletedRef.current = false;
    holdTimersRef.current.forEach((t, k) => {
      if (k.includes("interval")) clearInterval(t as ReturnType<typeof setInterval>);
      else clearTimeout(t as ReturnType<typeof setTimeout>);
    });
    holdTimersRef.current.clear();
    activeKeysRef.current.clear();

    startNewGame().then((result) => {
      if (!result) return;
      startTimeRef.current = Date.now();
      applyState({
        ...initialGameState(),
        piece: result.piece,
        nextPiece: result.nextPiece,
      });
    });
  }, [startNewGame, applyState]);

  // STOP: abandons the game in progress (or the in-flight start request)
  // and returns to the idle state, with no visible piece.
  const stopGame = useCallback(() => {
    gameGenerationRef.current += 1; // invalidates any pending startNewGame
    gameCompletedRef.current = false;
    holdTimersRef.current.forEach((t, k) => {
      if (k.includes("interval")) clearInterval(t as ReturnType<typeof setInterval>);
      else clearTimeout(t as ReturnType<typeof setTimeout>);
    });
    holdTimersRef.current.clear();
    activeKeysRef.current.clear();
    setReady(false);
    setLoading(false);
    applyState(initialGameState());
  }, [applyState]);

  return {
    // state
    board,
    piece,
    nextPiece,
    pos,
    lines,
    linesTarget: LINES_TARGET,
    elapsedMs,
    gameCompleted,
    gameOver,
    lockVisual,
    lockBoard,
    ready,
    loading,
    // actions
    moveLeft,
    moveRight,
    softDrop,
    rotateLeft,
    rotateRight,
    startGame,
    stopGame,
    startRepeat,
    stopRepeat,
  };
}
